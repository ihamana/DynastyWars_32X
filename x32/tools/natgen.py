#!/usr/bin/env python3
"""(V3.6) native routine list: finds the object-list skip loops in the arcade code
   head: tst.b/w (d,An) ; beq L ; ... L: lea (s,An),An ; dbra Dk,head
and writes tools/natlist.txt (entry + continuation addresses, for x68.py NATLIST) and gen/nat_tab.h (nat_sw cases).
The hand-written natives in gen/nat.c are listed in HAND below."""
import json, re, sys
d = json.load(open('/tmp/dw/code.json')); code = {int(k): v for k, v in d['code'].items()}
HAND = {            # entry: continuations (besides rts / jmp targets)
    0x46B4: [], 0x46E8: [],
    0x4F2A: [],
    0x6354: [0x636A],
    0x524: [0x540],
    0x4143A: [0x41448],
    0x41456: [0x41478],
    0x48202: [0x4825E],
    0x326C: [0x32AE, 0x3288],
    0x32AE: [0x32C8],
    0x447C4: [0x44828],
    0xB06E: [],                 # V2.6 sprite table (nat_b06e; was hooked in cpu_run)
}
skips = []
for pc, (ln, txt) in sorted(code.items()):
    m = re.match(r'tst\.([bw])\s+\(\$([0-9a-f]+),(A\d)\)$', txt)
    if not m: continue
    sz, dd, an = m.group(1), int(m.group(2), 16), m.group(3)
    b = pc + ln
    if b not in code: continue
    m2 = re.match(r'beq(\.[sw])?\s+\$([0-9a-f]+)$', code[b][1])
    if not m2: continue
    L = int(m2.group(2), 16)
    if L not in code: continue
    m3 = re.match(r'lea\s+\(\$([0-9a-f]+),%s\), %s$' % (an, an), code[L][1])
    if not m3: continue
    D = L + code[L][0]
    if D not in code: continue
    m4 = re.match(r'dbra\s+(D\d), \$([0-9a-f]+)$', code[D][1])
    if not m4 or int(m4.group(2), 16) != pc: continue
    skips.append((pc, sz, dd, int(an[1]), int(m3.group(1), 16), int(m4.group(1)[1]), b + code[b][0], D + code[D][0]))
with open('/dw/x32/tools/natlist.txt', 'w') as f:
    for a, cs in sorted(HAND.items()): f.write('%X %s\n' % (a, ' '.join('%X' % c for c in cs)))
    for s in skips: f.write('%X %X %X   # skip loop\n' % (s[0], s[6], s[7]))
with open('/dw/x32/gen/nat_tab.h', 'w') as f:
    f.write('/* generated by tools/natgen.py: object-list skip loops (nat.c nskip) */\n')
    for pc, sz, dd, an, st, dn, act, ex in skips:
        f.write('NATF(%X, nskip(%d, 0x%X, %d, 0x%X, %d, 0x%X, 0x%X))\n' % (pc, sz == 'w', dd, an, st, dn, act, ex))
print('skip loops', len(skips), 'hand', len(HAND))
