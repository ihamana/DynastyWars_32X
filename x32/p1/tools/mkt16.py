# V2.8: generates sh2/t16.s, the full-width rows of a 16x16 sprite tile (hand-written SH-2, see render.c draw_tile16)
#  void t16_<m>(u8 *base, const u8 *src, int n, const u16 *T, int sstep)
#  m = fx * 4 + (sx & 3); base = the overwrite image address of pixel 0 rounded down to 4; T = sp2 + 128 (signed byte index)
#  src: the first row's 8 bytes (16 4-bit pixels, 15 = transparent); sstep: +8 / -8 (fy) per row
# V3.1: t16d_<m>(..., int sstep, u32 mask): the same, every stored long ANDed with mask (0xFF00FF00 / 0x00FF00FF:
#  every other pixel), inverted each row: the flames drawn half (a checkerboard, the arcade shows them every other frame)
#  (in the cart: .rom2ui)
import sys
out = []
def e(s): out.append('\t' + s)
def lk(d, fx, j):          # pixel pair j (0-7) of the row into register d (low 16 bits)
    if fx:
        e('mov.b @(%d,r5),r0' % (7 - j)); e('add r0,r0'); e('mov.w @(r0,r7),%s' % d); e('swap.b %s,%s' % (d, d))
    else:
        e('mov.b @r5+,r0'); e('add r0,r0'); e('mov.w @(r0,r7),%s' % d)
def pair(d, fx, j):        # pairs j, j+1 as one long into d
    lk('r1', fx, j); lk(d, fx, j + 1); e('shll16 %s' % d); e('xtrct r1,%s' % d)
def gen(m, dith):
    fx, al = m >> 2, m & 3
    n = ('t16d_%d' if dith else 't16_%d') % m; L = ('.Ld%d' if dith else '.L%d') % m
    def st(r, ofs):
        if dith: e('and r12,%s' % r)
        e('mov.l %s,@(%d,r4)' % (r, ofs) if ofs else 'mov.l %s,@r4' % r)
    out.append('\t.align 2\n\t.global _%s\n_%s:' % (n, n))
    regs = ('r8', 'r9', 'r10', 'r11') + (('r12',) if dith else ())
    for r in regs: e('mov.l %s,@-r15' % r)
    e('mov.l @(%d,r15),r11' % (4 * len(regs)))
    if dith: e('mov.l @(%d,r15),r12' % (4 * len(regs) + 4))
    e('mov #80,r2'); e('shll2 r2')
    if not fx: e('mov r11,r3'); e('add #-8,r3')
    if al == 2: e('mov #0,r9')
    out.append('%s_row:' % L)
    e('mov.l @r5,r1'); e('mov.l @(4,r5),r0'); e('and r1,r0'); e('cmp/eq #-1,r0'); e('bt %s_skip' % L)
    if al == 0:
        for j in range(4): pair('r8', fx, 2 * j); st('r8', 4 * j)
    elif al == 2:
        lk('r8', fx, 0); e('shll16 r8'); e('xtrct r9,r8'); st('r8', 0)
        for j in range(3): pair('r8', fx, 1 + 2 * j); st('r8', 4 + 4 * j)
        lk('r8', fx, 7); e('shll16 r8'); st('r8', 16)
    else:
        for j in range(4):
            pair('r8', fx, 2 * j)
            e('mov r8,r9')
            if al == 1: e('shlr8 r9')
            else: e('shlr16 r9'); e('shlr8 r9')
            if j: e('or r10,r9')
            st('r9', 4 * j)
            e('mov r8,r10')
            if al == 1: e('shll16 r10'); e('shll8 r10')
            else: e('shll8 r10')
        st('r10', 16)
    e('add %s,r5' % ('r11' if fx else 'r3'))
    out.append('%s_next:' % L)
    if dith: e('not r12,r12')
    e('dt r6'); e('bf.s %s_row' % L); e('add r2,r4')
    for r in reversed(regs[1:]): e('mov.l @r15+,%s' % r)
    e('rts'); e('mov.l @r15+,r8')
    out.append('%s_skip:' % L)
    e('bra %s_next' % L); e('add r11,r5')
out.append('\t.section .nathot,"ax"')
for m in range(8): gen(m, False)
out.append('\t.section .rom2ui,"ax"')
for m in range(8): gen(m, True)
open(sys.argv[1], 'w').write('! generated by tools/mkt16.py\n' + '\n'.join(out) + '\n')
