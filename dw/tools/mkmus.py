# Build MSU-MD audio tracks from the offline renders.
#   loops: period from spectral features, refined at sample level; loop part stretched to a whole number
#          of CD sectors (588 samples) so the MSU loop offset is exact.
#   one-shots: trimmed after the last audible second.
# out: <outdir>/tNN.wav (44.1k stereo) + mus_tab.s  (cmd, track, loop offset in sectors; 0 = play once)
import numpy as np, wave, sys, os
from scipy.signal import resample
SRC=os.environ.get('MUSSRC','/tmp/dw/mus/')
OUT=sys.argv[1]; os.makedirs(OUT,exist_ok=True)
LOOPS=[0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x15]
ONES=[0x01,0x0E,0x0F,0x10,0x11,0x12,0x13,0x14,0x16,0x17,0x18,0x19,0x1A,0x1B,0x1C]
def load(fn):
    w=wave.open(fn); a=np.frombuffer(w.readframes(w.getnframes()),np.int16).reshape(-1,2).astype(np.float32); return a
def save(fn,a):
    w=wave.open(fn,'wb'); w.setnchannels(2); w.setsampwidth(2); w.setframerate(44100)
    w.writeframes(np.clip(np.round(a),-32768,32767).astype(np.int16).tobytes()); w.close()
def feats(m,hop=1024,N=2048):
    idx=np.arange(0,len(m)-N,hop)
    fr=np.stack([m[i:i+N] for i in idx])*np.hanning(N)
    return np.log1p(np.abs(np.fft.rfft(fr,axis=1))[:,:256])
def find_loop(a):
    m=a.mean(1); hop=1024; F=feats(m); n=len(F); fps=44100/hop
    W=int(40*fps)
    tail=F[n-W:]
    Ls=np.arange(int(8*fps),n-W)
    D=np.array([np.mean((F[n-W-L:n-L]-tail)**2) for L in Ls])
    d0=D.min()
    # candidate lags: distinct local minima of the feature distance
    order=np.argsort(D); cands=[]
    for i in order:
        L=int(Ls[i])
        if all(abs(L-c)>fps*2 for c in cands): cands.append(L)
        if len(cands)>=10: break
    t0=len(m)-44100*12; N=44100*4; ref=m[t0:t0+N]; rn=np.dot(ref,ref)
    def refine(L):
        P=L*hop; bc=(-1,0)
        for dl in range(-1536,1537):
            seg=m[t0-P+dl:t0-P+dl+N]
            c=np.dot(ref,seg)/np.sqrt(np.dot(seg,seg)*rn+1e-9)
            if c>bc[0]: bc=(c,dl)
        return P-bc[1],bc[0]
    res=[(L,)+refine(L) for L in cands if L*hop+44100*13<t0]
    cmax=max(r[2] for r in res)
    L,P,corr=min((r for r in res if r[2]>=cmax-0.01),key=lambda r:r[0])
    bestc=(corr,0)
    # earliest start: windows of 0.5 s that repeat one period later
    w=22050; s=len(m)-P-w
    def err(s): x=m[s:s+w]; y=m[s+P:s+P+w]; return np.mean((x-y)**2)/(np.mean(x*x)+1e3)
    ref=np.median([err(len(m)-P-w-k*w) for k in range(20)])
    thr=max(6*ref,0.03)
    K=(len(m)-P-w)//w
    good=np.array([err(k*w)<thr for k in range(K)])
    suf=np.cumsum(good[::-1])[::-1]/np.arange(K,0,-1)
    k0=next((k for k in range(K) if good[k] and suf[k]>=0.9),None)
    if k0 is None: return None
    lo,hi=max(k0*w-w,0),k0*w
    while hi-lo>64:
        mid=(lo+hi)//2
        if err(mid)<thr: hi=mid
        else: lo=mid
    print('   ref err %.4f thr %.4f good %.2f'%(ref,thr,good.mean()))
    return hi,P,bestc[0],d0
tab=[]
for c in [int(x,16) for x in sys.argv[2:]] or LOOPS:
    fn=SRC+'L%02X.wav'%c
    if not os.path.exists(fn): fn=SRC+'c%02X.wav'%c
    a=load(fn)
    r=find_loop(a)
    if r is None or r[2]<0.95 or r[0]>len(a)//3:
        print('cmd %02X: no reliable loop -> whole render loops'%c, r and (r[0]/44100,r[1]/44100,r[2]))
        st,P,corr,d0=0,len(a)//588*588,0,0
    else: st,P,corr,d0=r
    st2=((st+587)//588)*588
    Pn=int(round(P/588))*588
    body=resample(a[st2:st2+P],Pn,axis=0)
    trk=np.concatenate([a[:st2],body])
    t=c+1
    save(OUT+'/t%02d.wav'%t,trk)
    tab.append((c,t,st2//588+1))
    print('cmd %02X start %.3fs period %.3fs corr %.4f featerr %.3f -> track %d loop sector %d len %.1fs'%(c,st/44100,P/44100,corr,d0,t,st2//588,len(trk)/44100))
for c in (ONES if len(sys.argv)<3 else []):
    a=load(SRC+'c%02X.wav'%c); m=np.abs(a).max(1)
    sec=[m[i:i+44100].max() for i in range(0,len(m),44100)]
    last=max(i for i,v in enumerate(sec) if v>300)
    end=min((last+1)*44100+22050,len(a))
    trk=a[:end].copy(); nf=11025; trk[-nf:]*=np.linspace(1,0,nf)[:,None]
    t=c+1; save(OUT+'/t%02d.wav'%t,trk); tab.append((c,t,0))
    print('cmd %02X one-shot %.1fs -> track %d'%(c,end/44100,t))
with open(OUT+'/mus_tab.s','w') as f:
    f.write('| generated by tools/mkmus.py: Mus { u8 cmd; u8 track; u16 loop_sector+1 (0 = play once) }\n    .balign 2\n    .global mus_tab, mus_n\nmus_tab:\n')
    for c,t,l in sorted(tab): f.write('    .byte 0x%02X, %d\n    .word %d\n'%(c,t,l))
    f.write('mus_n: .word %d\n'%len(tab))
